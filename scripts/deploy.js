const { ethers } = require('hardhat');

async function main() {
  const owners = [process.env.OWNER_1, process.env.OWNER_2].filter(Boolean);

  if (owners.length < 2) {
    throw new Error('Set OWNER_1 and OWNER_2 in your .env before deploying.');
  }

  const AssetManager = await ethers.getContractFactory('AssetManager');
  const assetManager = await AssetManager.deploy(owners);

  await assetManager.waitForDeployment();

  console.log('AssetManager deployed to:', await assetManager.getAddress());
  console.log('Authorized owners:', owners);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});

























































































































































































































































































